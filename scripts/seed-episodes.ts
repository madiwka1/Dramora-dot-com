// Prints the tags/episodes/choices block of supabase/seed.sql from src/data/demoEpisodes.ts.
// Run: node scripts/seed-episodes.ts   (Node 23.6+ runs .ts directly), then paste over the generated block.
import { choiceRows, demoChoices, demoEpisodes, demoTags } from '../src/data/demoEpisodes.ts'

const q = (s: string) => `'${s.replaceAll("'", "''")}'`
// Episode key → (number, is_branch): '3b' = branch episode 3.
const key = (k: string) => `${parseInt(k)}, ${k.endsWith('b')}`

console.log('-- Generated by scripts/seed-episodes.ts from src/data/demoEpisodes.ts. Do not edit by hand.')
for (const [slug, tags] of Object.entries(demoTags)) {
  console.log(`update public.dramas set tags = array[${tags.map(q).join(', ')}] where slug = ${q(slug)};`)
}
console.log('\ninsert into public.episodes (drama_id, number, title, synopsis, duration_sec, is_branch)')
console.log('select d.id, v.number, v.title, v.synopsis, v.duration_sec, v.is_branch')
console.log('from public.dramas d join (values')
console.log(
  demoEpisodes
    .map((e) => `  (${q(e.slug)}, ${e.number}, ${q(e.title)}, ${q(e.synopsis)}, ${e.durationSec}, ${!!e.isBranch})`)
    .join(',\n'),
)
console.log(') as v(slug, number, title, synopsis, duration_sec, is_branch) on v.slug = d.slug;')

console.log('\n-- 3 options per decision point; the group (or the player whose turn it is) picks one.')
console.log('insert into public.choices (episode_id, label, next_episode_id, sort, video_url)')
console.log('select src.id, v.label, dst.id, v.sort, v.video_url')
console.log('from (values')
console.log(
  Object.keys(demoChoices)
    .flatMap((slug) => choiceRows(slug).map((c) => `  (${q(slug)}, ${key(c.src)}, ${q(c.label)}, ${key(c.dst)}, ${c.sort}, ${c.video ? q(c.video) : 'null::text'})`))
    .join(',\n'),
)
console.log(') as v(slug, src_number, src_branch, label, dst_number, dst_branch, sort, video_url)')
console.log('join public.dramas d on d.slug = v.slug')
console.log('join public.episodes src on src.drama_id = d.id and src.number = v.src_number and src.is_branch = v.src_branch')
console.log('join public.episodes dst on dst.drama_id = d.id and dst.number = v.dst_number and dst.is_branch = v.dst_branch;')
